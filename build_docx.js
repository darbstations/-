/* ---------- عناصر ---------- */
/* في سياق RTL تُعامَل علامة % كمحرف محايد فتنتقل إلى يسار الرقم.
   إحاطة الرقم + % بعلامة LRM من الجهتين تُثبّت الترتيب الصحيح (مُختبَر). */
const LRM = '\u200E';
// A leading sign and a trailing % are both bidi neutrals, so Word strands them at
// the far end of the run ("53%+" for "+53%", "1,200 ر.س+" for "+1,200 ر.س").
// Isolate the whole signed/percent number with LRM on both sides.
// A hyphen that follows a digit is a range separator (15-25), not a minus.
const NUM = /([+\u2212]\d[\d,\.]*%?|(?<!\d)-\d[\d,\.]*%?|\d[\d,\.]*%)/g;
const fixPct = (t) => String(t).replace(NUM, LRM + '$1' + LRM);

// o.ltr: a formula reads left to right on its own; inside an RTL run Word reorders
// its operands and brackets ("235 − 219" comes out "219 − 235").
const run = (text, o={}) => [ new TextRun({
  text: o.ltr ? String(text) : fixPct(text), rightToLeft: !o.ltr,
  font: o.font || FB, size: o.size || 20, bold: !!o.bold,
  color: o.color || INK, ...(o.break?{break:o.break}:{}),
}) ];

const para = (children, o={}) => new Paragraph({
  bidirectional: !o.ltr,
  alignment: o.align || AlignmentType.START,
  spacing: { before: o.before ?? 0, after: o.after ?? 120, line: o.line ?? 300, lineRule: 'auto' },
  ...(o.border?{border:o.border}:{}),
  ...(o.shading?{shading:o.shading}:{}),
  ...(o.indent?{indent:o.indent}:{}),
  ...(o.keepNext?{keepNext:true}:{}),
  ...(o.pageBreakBefore?{pageBreakBefore:true}:{}),
  children: children.flat(),
});

const P  = (text, o={}) => para([run(text, { size:o.size||20, color:o.color||INK2, bold:o.bold })], o);

const KICK = (t, brk) => para([run(t, { font:FH, size:16, color:ORANGE_D, bold:true })],
                              { after:40, keepNext:true, pageBreakBefore:!!brk });

const H2 = (kicker, title, brk=true) => [
  KICK(kicker, brk),
  para([run(title, { font:FH, size:30, color:INK, bold:true })],
       { after:120, keepNext:true,
         border:{ bottom:{ style:BorderStyle.SINGLE, size:10, color:ORANGE, space:6 } } }),
];

const H3 = (title) => para([run(title, { font:FH, size:22, color:INK, bold:true })],
                           { before:150, after:70, keepNext:true });

const BUL = (items, color) => items.map(x => new Paragraph({
  bidirectional: true, bullet: { level: 0 },
  spacing: { after: 50, line: 280, lineRule: 'auto' },
  children: run(x, { size: 19, color: color || INK2 }),
}));

/* ---------- جداول ---------- */
const cell = (children, o={}) => new TableCell({
  children, width: { size: o.w, type: WidthType.DXA },
  margins: { top: 74, bottom: 74, left: 110, right: 110 },
  verticalAlign: VerticalAlign.CENTER,
  shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill, color: 'auto' } : undefined,
  borders: { top: thin(), bottom: thin(), left: thin(), right: thin() },
  ...(o.span?{columnSpan:o.span}:{}),
});

function TBL(headers, rows, widths, opt={}) {
  const head = new TableRow({
    tableHeader: true,
    children: headers.map((h,i) => cell(
      [para([run(h, { font:FH, size:17, color:INK2, bold:true })],
            { after:0, align: i===0?AlignmentType.START:(opt.center?AlignmentType.CENTER:AlignmentType.START) })],
      { w: widths[i], fill: PAPER2 })),
  });
  /* cantSplit: a row moves to the next page whole, never splitting its text mid-cell */
  const body = rows.map((r, ri) => new TableRow({
    cantSplit: true,
    children: r.map((c,i) => {
      const v = (c && typeof c === 'object' && !Array.isArray(c)) ? c : { text: c };
      return cell([para([run(String(v.text), {
          size: 18, color: v.color || (i===0?INK:INK2), bold: v.bold || i===0, font: v.font || FB, ltr: v.ltr })],
        { after:0, ltr: v.ltr,
          align: v.align || (i===0?AlignmentType.START:(opt.center?AlignmentType.CENTER:AlignmentType.START)) })],
        { w: widths[i], fill: v.fill || (ri%2 ? 'FAFAFB' : undefined) });
    }),
  }));
  return new Table({
    columnWidths: widths, width: { size: widths.reduce((a,b)=>a+b,0), type: WidthType.DXA },
    visuallyRightToLeft: true, rows: [head, ...body],
  });
}

/* بطاقات المؤشرات */
function KPI(cards) {
  const w = Math.floor(W / cards.length);
  return new Table({
    columnWidths: cards.map(()=>w), width:{ size:w*cards.length, type:WidthType.DXA },
    visuallyRightToLeft: true,
    rows: [ new TableRow({ children: cards.map(c => new TableCell({
      width:{ size:w, type:WidthType.DXA },
      margins:{ top:150, bottom:150, left:120, right:120 },
      shading:{ type:ShadingType.CLEAR, fill:'FFFFFF', color:'auto' },
      borders:{ top:thin(), bottom:thin(), left:thin(), right:thin() },
      children:[
        para([run(c.num, { font:FH, size:34, color:ORANGE_D, bold:true })], { after:40, align:AlignmentType.CENTER }),
        para([run(c.lbl, { font:FH, size:18, color:INK, bold:true })], { after:40, align:AlignmentType.CENTER }),
        para([run(c.cap, { size:15, color:INK3 })], { after:0, align:AlignmentType.CENTER }),
      ],
    }))})],
  });
}

/* لوحة ملوّنة */
function NOTE(title, lines, tone='orange') {
  const map = { orange:[ORANGE,ORANGE_BG,ORANGE_D], rose:[ROSE,ROSE_BG,ROSE], green:[GREEN,GREEN_BG,GREEN] };
  const [bar, bg, fg] = map[tone];
  return new Table({
    columnWidths:[W], width:{ size:W, type:WidthType.DXA }, visuallyRightToLeft:true,
    /* cantSplit: the box moves to the next page whole rather than orphaning a bullet */
    rows:[ new TableRow({ cantSplit:true, children:[ new TableCell({
      width:{ size:W, type:WidthType.DXA },
      margins:{ top:170, bottom:170, left:180, right:180 },
      shading:{ type:ShadingType.CLEAR, fill:bg, color:'auto' },
      borders:{ top:NONE, bottom:NONE, left:NONE,
                right:{ style:BorderStyle.SINGLE, size:18, color:bar } },
      children:[ para([run(title, { font:FH, size:21, color:fg, bold:true })], { after:90 }),
                 ...lines.map(l => new Paragraph({ bidirectional:true, bullet:{ level:0 },
                   spacing:{ after:70, line:290, lineRule:'auto' }, children: run(l, { size:19, color:INK }) })) ],
    })]})],
  });
}

/* شبكة 2×2 للنتائج والتحديات والفرص والتوصيات */
function QUAD(boxes) {
  const w = Math.floor(W/2);
  const box = (b) => new TableCell({
    width:{ size:w, type:WidthType.DXA },
    margins:{ top:130, bottom:130, left:150, right:150 },
    shading:{ type:ShadingType.CLEAR, fill:'FBFBFC', color:'auto' },
    borders:{ top:thin(), bottom:thin(), left:thin(), right:thin() },
    children:[
      para([run(b.title, { font:FH, size:19, color:b.color, bold:true })], { after:70 }),
      ...b.items.map(x => new Paragraph({ bidirectional:true, bullet:{ level:0 },
        spacing:{ after:45, line:270, lineRule:'auto' },
        children: run(x, { size:17, color:INK2 }) })),
    ],
  });
  return new Table({
    columnWidths:[w,w], width:{ size:w*2, type:WidthType.DXA }, visuallyRightToLeft:true,
    /* cantSplit: a row moves to the next page whole, instead of leaving a stub behind */
    rows:[ new TableRow({ cantSplit:true, children:[ box(boxes[0]), box(boxes[1]) ] }),
           new TableRow({ cantSplit:true, children:[ box(boxes[2]), box(boxes[3]) ] }) ],
  });
}

