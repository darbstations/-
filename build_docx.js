/* ---------- جداول ---------- */
const cell = (children, o={}) => new TableCell({
  children, width: { size: o.w, type: WidthType.DXA },
  margins: { top: 90, bottom: 90, left: 110, right: 110 },
  verticalAlign: VerticalAlign.CENTER,
  shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill, color: 'auto' } : undefined,
  borders: { top: thin(), bottom: thin(), left: thin(), right: thin() },
  ...(o.span?{columnSpan:o.span}:{}),
});

function TBL(headers, rows, widths, opt={}) {
  const head = new TableRow({
    tableHeader: true,
    children: headers.map((h,i) => cell(
      [para([run(h, { font:FH, size:17, color:INK2, bold:true })],
            { after:0, align: i===0?AlignmentType.START:(opt.center?AlignmentType.CENTER:AlignmentType.START) })],
      { w: widths[i], fill: PAPER2 })),
  });
  const body = rows.map((r, ri) => new TableRow({
    children: r.map((c,i) => {
      const v = (c && typeof c === 'object' && !Array.isArray(c)) ? c : { text: c };
      return cell([para([run(String(v.text), {
          size: 18, color: v.color || (i===0?INK:INK2), bold: v.bold || i===0, font: v.font || FB })],
        { after:0, align: v.align || (i===0?AlignmentType.START:(opt.center?AlignmentType.CENTER:AlignmentType.START)) })],
        { w: widths[i], fill: v.fill || (ri%2 ? 'FAFAFB' : undefined) });
    }),
  }));
  return new Table({
    columnWidths: widths, width: { size: widths.reduce((a,b)=>a+b,0), type: WidthType.DXA },
    visuallyRightToLeft: true, rows: [head, ...body],
  });
}

/* بطاقات المؤشرات */
function KPI(cards) {
  const w = Math.floor(W / cards.length);
  return new Table({
    columnWidths: cards.map(()=>w), width:{ size:w*cards.length, type:WidthType.DXA },
    visuallyRightToLeft: true,
    rows: [ new TableRow({ children: cards.map(c => new TableCell({
      width:{ size:w, type:WidthType.DXA },
      margins:{ top:150, bottom:150, left:120, right:120 },
      shading:{ type:ShadingType.CLEAR, fill:'FFFFFF', color:'auto' },
      borders:{ top:thin(), bottom:thin(), left:thin(), right:thin() },
      children:[
        para([run(c.num, { font:FH, size:34, color:ORANGE_D, bold:true })], { after:40, align:AlignmentType.CENTER }),
        para([run(c.lbl, { font:FH, size:18, color:INK, bold:true })], { after:40, align:AlignmentType.CENTER }),
        para([run(c.cap, { size:15, color:INK3 })], { after:0, align:AlignmentType.CENTER }),
      ],
    }))})],
  });
}

/* لوحة ملوّنة */
function NOTE(title, lines, tone='orange') {
  const map = { orange:[ORANGE,ORANGE_BG,ORANGE_D], rose:[ROSE,ROSE_BG,ROSE], green:[GREEN,GREEN_BG,GREEN] };
  const [bar, bg, fg] = map[tone];
  return new Table({
    columnWidths:[W], width:{ size:W, type:WidthType.DXA }, visuallyRightToLeft:true,
    rows:[ new TableRow({ children:[ new TableCell({
      width:{ size:W, type:WidthType.DXA },
      margins:{ top:170, bottom:170, left:180, right:180 },
      shading:{ type:ShadingType.CLEAR, fill:bg, color:'auto' },
      borders:{ top:NONE, bottom:NONE, left:NONE,
                right:{ style:BorderStyle.SINGLE, size:18, color:bar } },
      children:[ para([run(title, { font:FH, size:21, color:fg, bold:true })], { after:90 }),
                 ...lines.map(l => new Paragraph({ bidirectional:true, bullet:{ level:0 },
                   spacing:{ after:70, line:290, lineRule:'auto' }, children: run(l, { size:19, color:INK }) })) ],
    })]})],
  });
}

/* شبكة 2×2 للنتائج والتحديات والفرص والتوصيات */
function QUAD(boxes) {
  const w = Math.floor(W/2);
  const box = (b) => new TableCell({
    width:{ size:w, type:WidthType.DXA },
    margins:{ top:130, bottom:130, left:150, right:150 },
    shading:{ type:ShadingType.CLEAR, fill:'FBFBFC', color:'auto' },
    borders:{ top:thin(), bottom:thin(), left:thin(), right:thin() },
    children:[
      para([run(b.title, { font:FH, size:19, color:b.color, bold:true })], { after:70 }),
      ...b.items.map(x => new Paragraph({ bidirectional:true, bullet:{ level:0 },
        spacing:{ after:45, line:270, lineRule:'auto' },
        children: run(x, { size:17, color:INK2 }) })),
    ],
  });
  return new Table({
    columnWidths:[w,w], width:{ size:w*2, type:WidthType.DXA }, visuallyRightToLeft:true,
    rows:[ new TableRow({ children:[ box(boxes[0]), box(boxes[1]) ] }),
           new TableRow({ children:[ box(boxes[2]), box(boxes[3]) ] }) ],
  });
}

